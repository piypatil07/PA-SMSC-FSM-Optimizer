# 2. PARSING HELPER FUNCTIONS
# =====================================================================
def parse_condition(cond_str):
    """Converts CSV boolean logic to Verilog syntax.
       Example: 'x8x9' -> 'x[8] && x[9]' | 'x8'' -> '!x[8]'"""
    terms = re.findall(r"x(\d+)('?)", cond_str)
    verilog_terms = []
    for num, prime in terms:
        if prime == "'":
            verilog_terms.append(f"!x[{num}]")
        else:
            verilog_terms.append(f"x[{num}]")
    return " && ".join(verilog_terms) if verilog_terms else "1'b1"

def parse_outputs(out_str):
    """Converts CSV output sets to a 12-bit Verilog binary literal.
       Example: 'y1y2y12' -> 12'b100000000011 (assuming y[12:1] indexing)"""
    out_bits = ['0'] * 12
    nums = re.findall(r"y(\d+)", out_str)
    for n in nums:
        idx = int(n) - 1
        if 0 <= idx < 12:
            out_bits[idx] = '1'
    # Reverse for MSB-first Verilog literal
    return "12'b" + "".join(reversed(out_bits))

# =====================================================================
# 3. VERILOG GENERATION ENGINE
# =====================================================================
def generate_structural_verilog(csv_filename, output_filename=None):
    # Group transitions by current_state
    transitions_by_state = {}
    with open(csv_filename, mode='r') as file:
        reader = csv.DictReader(file)
        for row in reader:
            curr = row['current_state'].strip()
            if curr not in transitions_by_state:
                transitions_by_state[curr] = []
            transitions_by_state[curr].append({
                'cond': row['input_condition'].strip(),
                'next': row['next_state'].strip(),
                'out': row['output_set'].strip()
            })

    # Group states by class
    classes = {i: [] for i in range(9)}
    for state, (cls, partial) in STATE_TO_CLASS_PARTIAL.items():
        classes[cls].append((state, partial))

    verilog_lines = []
    verilog_lines.append("// =====================================================================")
    verilog_lines.append("// AUTO-GENERATED LEVEL 1 PARTIAL FUNCTIONS")
    verilog_lines.append("// Generated by verilog_generator.py (PA-SMSC Toolchain)")
    verilog_lines.append("// =====================================================================\n")

    for cls_num in range(9):
        verilog_lines.append(f"    // --- LEVEL 1, CLASS {cls_num} ---")
        verilog_lines.append(f"    always @(*) begin")
        verilog_lines.append(f"        D{cls_num}_partial = 7'b0; // Default to prevent latches")
        verilog_lines.append(f"        Y{cls_num}_partial = 12'b0;")
        verilog_lines.append(f"        case (partial_code)")
        
        # Sort states by their partial code for clean Verilog formatting
        for state, partial_code in sorted(classes[cls_num], key=lambda x: x[1]):
            verilog_lines.append(f"            3'b{partial_code}: begin // State {state}")
            trans = transitions_by_state.get(state, [])
            
            for i, t in enumerate(trans):
                verilog_cond = parse_condition(t['cond'])
                verilog_next = f"7'b{STATE_TO_MSC[t['next']]}"
                verilog_out = parse_outputs(t['out'])
                
                if i == 0:
                    verilog_lines.append(f"                if ({verilog_cond}) begin")
                else:
                    verilog_lines.append(f"                else if ({verilog_cond}) begin")
                    
                verilog_lines.append(f"                    D{cls_num}_partial = {verilog_next};")
                verilog_lines.append(f"                    Y{cls_num}_partial = {verilog_out};")
                verilog_lines.append(f"                end")
            
            # Fallback condition to prevent latches and ensure safe state holding
            verilog_lines.append(f"                else begin")
            verilog_lines.append(f"                    D{cls_num}_partial = 7'b{STATE_TO_MSC[state]}; // Hold state")
            verilog_lines.append(f"                    Y{cls_num}_partial = 12'b0;")
            verilog_lines.append(f"                end")
            verilog_lines.append(f"            end")
            
        verilog_lines.append(f"            default: begin")
        verilog_lines.append(f"                D{cls_num}_partial = 7'b0;")
        verilog_lines.append(f"                Y{cls_num}_partial = 12'b0;")
        verilog_lines.append(f"            end")
        verilog_lines.append(f"        endcase")
        verilog_lines.append(f"    end\n")

    # Output to Terminal
    output_text = "\n".join(verilog_lines)
    print(output_text)

    # Optional: Save directly to a file for professional workflow
    if output_filename:
        with open(output_filename, 'w') as f:
            f.write(output_text)
        print(f"\n✅ Successfully saved generated Verilog to '{output_filename}'")

